const MAX_FINDINGS = 10;
const MAX_NAMES = 3;
const KINDS: EntityKind[] = ['tag', 'trigger', 'variable'];
const kindLabel = (k: EntityKind) => t(k === 'tag' ? 'tags' : k === 'trigger' ? 'triggers' : 'variables');

export function buildCompactReport(input: ReportInput): string {
  const { context, diff, lint } = input;
  const out: string[] = [`# ${t('title')}${context.publicId ? ` – ${context.publicId}` : ''}`, ''];
  out.push(
    [
      context.publicId && `**${t('container')}:** ${context.publicId}`,
      diff && `**${t('scope')}:** ${diff.plan.base.label} → ${diff.plan.target.label}`,
      `**${t('generated')}:** ${formatDateTime(Date.now())}`,
    ]
      .filter(Boolean)
      .join('  \n'),
    '',
  );

  out.push(`## ${t('summary')}`, '');
  if (input.aiSummary?.trim()) out.push(input.aiSummary.trim(), '', `### ${t('figures')}`, '');
  if (diff) out.push(`- **${t('changes')}:** ${changeCounts(diff)}`);
  if (diff?.timeline.length) out.push(`- **${t('publications')}:** ${diff.timeline.map((x) => `v${x.versionId}${x.name ? ` (${x.name})` : ''}`).join(', ')}`);
  if (lint) out.push(`- ${t('qa', { critical: lint.counts.critical, warning: lint.counts.warning, info: lint.counts.info })}`);
  if (lint?.sst) out.push(`- **${t('sst')}:** ${sstLine(lint)}`);
  out.push('');

  if (lint) {
    out.push(`## ${t('findings')}`, '');
    const important = lint.findings.filter((f) => f.severity !== 'info');
    if (!important.length) out.push(t('noFindings'));
    for (const f of important.slice(0, MAX_FINDINGS)) out.push(findingLine(f));
    if (important.length > MAX_FINDINGS) out.push(`- ${t('more', { n: important.length - MAX_FINDINGS })}`);
    if (lint.counts.info) out.push('', `_${t('infoCount', { n: lint.counts.info })}_`);
    out.push('');
  }

  out.push(...purchaseSection(input.snapshot, diff, input.templates, true));

  if (diff?.entities.length) {
    out.push(`## ${t('changes')}`, '');
    for (const kind of KINDS) {
      const line = changeGroupLine(diff.entities.filter((e) => e.kind === kind));
      if (line) out.push(`- **${kindLabel(kind)}** – ${line}`);
    }
    out.push('');
  }

  out.push('---', `_${t('footer')}_`);
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}

function changeCounts(diff: DiffResult): string {
  if (!diff.entities.length) return t('noChanges');
  return KINDS.map((kind) => {
    const list = diff.entities.filter((e) => e.kind === kind);
    if (!list.length) return null;
    const n = (s: EntityDiff['status']) => list.filter((e) => e.status === s).length;
    const parts = [n('added') && `+${n('added')}`, n('modified') && `~${n('modified')}`, n('removed') && `−${n('removed')}`].filter(Boolean);
    return `${kindLabel(kind)} ${parts.join(' ')}`;
  })
    .filter(Boolean)
    .join(' · ');
}

/** "added (11): A, B, C +8 more · changed (4): …" */
function changeGroupLine(list: EntityDiff[]): string {
  return (['added', 'modified', 'removed'] as const)
    .map((status) => {
      const names = list.filter((e) => e.status === status).map((e) => e.name);
      if (!names.length) return null;
      const shown = names.slice(0, MAX_NAMES).join(', ');
      const rest = names.length > MAX_NAMES ? ` ${t('plusMore', { n: names.length - MAX_NAMES })}` : '';
      return `${t(status)} (${names.length}): ${shown}${rest}`;
    })
    .filter(Boolean)
    .join(' · ');
}

function findingLine(f: Finding): string {
  const icon = f.severity === 'critical' ? '🔴' : '🟠';
  const names = f.entities.map((e) => e.name);
  // Some titles already name the tag – don't repeat it.
  const who = names.length && !names.some((n) => f.title.includes(n)) ? ` – ${names.slice(0, MAX_NAMES).join(', ')}${names.length > MAX_NAMES ? ` ${t('plusMore', { n: names.length - MAX_NAMES })}` : ''}` : '';
  // Long trigger conditions in event labels ("purchase [{{x}} NOT matchRegex …]") are shortened here.
  const title = f.title.replace(/ \[[^\]]{20,}\]/g, ' […]');
  return `- ${icon} ${title}${who}`;
}

function sstLine(lint: LintResult): string {
  const routes = lint.sst!.routes;
  const count = (bridge: string) => routes.filter((r) => r.bridge === bridge).length;
  const parts = [count('GA4') && `GA4 Bridge ${count('GA4')}`, count('Data Tag') && `Data Tag ${count('Data Tag')}`, count('Inny') && `+${count('Inny')}`].filter(Boolean);
  return `${lint.sst!.hosts.join(', ')} (${parts.join(', ')})`;
}
