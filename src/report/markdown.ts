// Builds the Markdown implementation report (Jira / Asana / ClickUp) from the last diff and QA run.
// Pure function: everything it needs is passed in.
import type { DiffResult, EntityDiff } from '../diff/diffEngine';
import { defineMessages, formatDateTime } from '../i18n';
import type { LintResult } from '../qa/linter';
import { describeSource, Resolver, sourceText, type Source } from '../qa/resolver';
import type { Finding, Severity } from '../qa/rules';
import { fieldUses, type SemanticField } from '../qa/semantics';
import type { Settings } from '../shared/storage';
import type { EntityKind, GtmContext, GtmTag, Snapshot } from '../shared/types';
import { buildCompactReport } from './compact';
import { purchaseSection } from './purchase';

export interface ReportInput {
  context: GtmContext;
  diff: DiffResult | null;
  lint: LintResult | null;
  /** Snapshot the values table is built from (diff target or QA scope). */
  snapshot: Snapshot | null;
  templates: Map<string, string>;
  settings: Settings;
  aiSummary?: string;
  options: ReportOptions;
}

export interface ReportOptions {
  /** Full report with tables and finding details; false = short report for tickets (default). */
  detailed: boolean;
  includeInfo: boolean;
  includeChangeList: boolean;
  maxDetailLines: number;
}

export const DEFAULT_REPORT_OPTIONS: ReportOptions = { detailed: false, includeInfo: false, includeChangeList: true, maxDetailLines: 8 };

