// Label maps are functions so they follow the active language.
const KIND_LABEL = (kind: EntityKind): string =>
  kind === 'tag' ? tr('kindTag') : kind === 'trigger' ? tr('kindTrigger') : tr('kindVariable');
const STATUS_ICON = { added: '➕', modified: '✏️', removed: '➖' } as const;
const STATUS_LABEL = (status: EntityDiff['status']): string =>
  status === 'added' ? tr('statusAdded') : status === 'modified' ? tr('statusModified') : tr('statusRemoved');
const SEVERITY_HEADER = (severity: Severity): string =>
  severity === 'critical' ? tr('sevCritical') : severity === 'warning' ? tr('sevWarning') : tr('sevInfo');
const VALUE_FIELDS: SemanticField[] = ['value', 'currency', 'transaction_id'];

export function buildReport(input: ReportInput): string {
  if (!input.options.detailed) return buildCompactReport(input);
  const { context, diff, lint, options } = input;
  const out: string[] = [];
  const container = [context.publicId, context.containerId && tr('containerId', { id: context.containerId })].filter(Boolean).join(' · ');

  out.push(`# ${tr('title')}${context.publicId ? ` – ${context.publicId}` : ''}`, '');
  const meta = [
    container && `**${tr('metaContainer')}:** ${container}`,
    diff && `**${tr('metaScope')}:** ${diff.plan.description} (${diff.plan.base.label} → ${diff.plan.target.label})`,
    lint && `**${tr('metaQa')}:** ${lint.scopeLabel}${lint.limitedTo !== undefined ? ` – ${tr('qaChangedOnly', { count: lint.limitedTo })}` : ''}`,
    `**${tr('metaGenerated')}:** ${formatDateTime(Date.now())}`,
  ].filter(Boolean);
  out.push(meta.join('  \n'), '');

  out.push(`## ${tr('summary')}`, '');
  if (input.aiSummary?.trim()) out.push(input.aiSummary.trim(), '', `### ${tr('statistics')}`, '');
  out.push(...summaryLines(diff, lint), '');

  if (diff?.timeline.length) {
    out.push(`## ${tr('publications')}`, '', tr('publicationsTable'), '|---|---|---|---|---|');
    for (const t of diff.timeline) out.push(`| v${t.versionId} | ${cell(t.name ?? '')} | ${cell(t.author ?? '')} | ${t.createdAt ? formatDateTime(t.createdAt) : ''} | ${t.changes.length} |`);
    out.push('');
  }

  const valueRows = valuesTable(input);
  if (valueRows.length) {
    out.push(
      `## ${tr('values')}`,
      '',
      diff ? tr('valuesNoteDiff') : tr('valuesNote'),
      '',
      tr('valuesTable'),
      '|---|---|---|---|---|---|---|---|',
      ...valueRows,
      '',
    );
  }

  out.push(...purchaseSection(input.snapshot, diff, input.templates));

  if (lint) {
    out.push(`## ${tr('qaFindings')}`, '');
    if (!lint.findings.length) out.push(tr('noFindings'), '');
    for (const severity of ['critical', 'warning', 'info'] as const) {
      const list = lint.findings.filter((f) => f.severity === severity);
      if (!list.length) continue;
      out.push(`### ${SEVERITY_HEADER(severity)} (${list.length})`, '');
      if (severity === 'info' && !options.includeInfo) {
        out.push(...list.map((f) => `- ${f.title}`), '');
        continue;
      }
      for (const f of list) out.push(...findingLines(f, options.maxDetailLines), '');
    }
    if (lint.warnings.length) out.push(...lint.warnings.map((w) => `> ⚠️ ${w}`), '');
  }

  if (lint?.sst) {
    out.push(`## ${tr('sstRouting', { hosts: lint.sst.hosts.join(', ') })}`, '', tr('sstTable'), '|---|---|---|---|---|');
    for (const r of lint.sst.routes) {
      out.push(`| ${r.bridge} | ${cell(r.tag.name)} | ${cell(r.events.join(', '))} | ${cell(r.fields.join(', '))} | ${cell(r.userData.join(', '))} |`);
    }
    out.push('');
  }

  if (diff && options.includeChangeList && diff.entities.length) {
    out.push(`## ${tr('changeList')}`, '');
    for (const kind of ['tag', 'trigger', 'variable'] as const) {
      const list = diff.entities.filter((e) => e.kind === kind);
      if (!list.length) continue;
      out.push(`### ${KIND_LABEL(kind)} (${list.length})`, '');
      out.push(...list.map((e) => changeLine(e, input.templates)), '');
    }
  }
  if (diff?.touchedButUnchanged.length) {
    out.push(`### ${tr('touchedButUnchanged')}`, '', ...diff.touchedButUnchanged.map((c) => `- ${c.name} (${c.entityType})`), '');
  }

  out.push('---', tr('footer'));
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}

// --- sections ------------------------------------------------------------------------

function summaryLines(diff: DiffResult | null, lint: LintResult | null): string[] {
  const lines: string[] = [];
  if (diff) {
    for (const kind of ['tag', 'trigger', 'variable'] as const) {
      const list = diff.entities.filter((e) => e.kind === kind);
      if (!list.length) continue;
      const n = (s: EntityDiff['status']) => list.filter((e) => e.status === s).length;
      const parts = [
        n('added') && tr('countAdded', { count: n('added') }),
        n('modified') && tr('countModified', { count: n('modified') }),
        n('removed') && tr('countRemoved', { count: n('removed') }),
      ];
      lines.push(`- **${KIND_LABEL(kind)}:** ${parts.filter(Boolean).join(', ')}`);
    }
    if (!diff.entities.length) lines.push(`- ${tr('noChanges')}`);
    if (diff.timeline.length) lines.push(`- **${tr('publicationsLabel')}:** ${diff.timeline.length} (${diff.timeline.map((t) => `v${t.versionId}`).join(', ')})`);
  }
  if (lint) {
    lines.push(`- **${tr('metaQa')}:** ${tr('qaCounts', { critical: lint.counts.critical, warning: lint.counts.warning, info: lint.counts.info })}`);
    const critical = lint.findings.filter((f) => f.severity === 'critical').slice(0, 5);
    for (const f of critical) lines.push(`  - 🔴 ${f.title}`);
  }
  return lines;
}

function findingLines(f: Finding, maxDetails: number): string[] {
  const lines = [`- **${f.title}**  `, `  ${f.message}`];
  const details = f.details.slice(0, maxDetails);
  if (details.length) {
    lines.push('  ```', ...details.map((d) => `  ${d}`), ...(f.details.length > maxDetails ? [`  ${tr('moreDetails', { count: f.details.length - maxDetails })}`] : []), '  ```');
  }
  return lines;
}

function changeLine(e: EntityDiff, templates: Map<string, string>): string {
  const type = templates.get(e.type) ?? e.type;
  const versions = e.touchedIn.length ? ` – v${e.touchedIn.join(', v')}` : '';
  const fields = e.status === 'modified' ? `: ${e.fields.map((f) => f.field).join(', ')}` : '';
  return `- ${STATUS_ICON[e.status]} ${STATUS_LABEL(e.status)} **${e.name}** (${type})${versions}${fields}`;
}

/** One row per tag that sends value / currency / transaction id. */
function valuesTable(input: ReportInput): string[] {
  const snap = input.snapshot;
  if (!snap) return [];
  const resolver = new Resolver(snap);
  const changed = input.diff ? new Map(input.diff.entities.filter((e) => e.kind === 'tag' && e.status !== 'removed').map((e) => [e.id, e.status])) : null;
  const tags = Object.values(snap.tags).filter((t) => !changed || changed.has(t.id));
  const rows: string[] = [];
  for (const t of tags.sort((a, b) => a.name.localeCompare(b.name, 'pl'))) {
    const uses = fieldUses(t, resolver).filter((u) => VALUE_FIELDS.includes(u.field));
    if (!uses.length) continue;
    const get = (field: SemanticField) => uses.find((u) => u.field === field);
    const value = get('value');
    rows.push(
      [
        cell(t.name) + (t.paused ? ` ${tr('paused')}` : ''),
        cell(input.templates.get(t.type) ?? t.type),
        changed ? STATUS_LABEL(changed.get(t.id) as 'added' | 'modified') : '',
        value ? cell(`${shortSource(value.resolved.source)}${valueType(value.resolved.source)}`) : '—',
        value ? grossNet(value.resolved.source, value.raw, input.settings) : '—',
        get('currency') ? cell(shortSource(get('currency')!.resolved.source)) : '—',
        get('transaction_id') ? cell(shortSource(get('transaction_id')!.resolved.source)) : '—',
        consentLabel(t),
      ].join(' | ').replace(/^/, '| ') + ' |',
    );
  }
  return rows;
}

function shortSource(s: Source): string {
  if (s.kind === 'dataLayer') return `dL: ${s.path}`;
  if (s.kind === 'constant' || s.kind === 'text') return `"${s.value}"`;
  return describeSource(s);
}

function valueType(s: Source): string {
  if (s.kind === 'constant' || s.kind === 'text') return /^-?\d+(\.\d+)?$/.test(s.value.trim()) ? ` ${tr('number')}` : ` ⚠️ ${tr('text')}`;
  if (s.kind === 'mixed') return ` ⚠️ ${tr('text')}`;
  return '';
}

function grossNet(s: Source, raw: string, settings: Settings): string {
  // Language-independent text, so the gross/net guess does not depend on the UI language.
  const text = `${sourceText(s)} ${raw}`.toLowerCase();
  const words = (list: string[]) => list.some((w) => new RegExp(`(^|[^a-z])${w}([^a-z]|$)`).test(text));
  const gross = words(settings.financialKeywords.gross);
  const net = words(settings.financialKeywords.net);
  if (gross && !net) return tr('gross');
  if (net && !gross) return tr('net');
  return tr('undetermined');
}

function consentLabel(t: GtmTag): string {
  if (t.consent?.status === 'needed') return t.consent.types.join(', ') || tr('consentRequired');
  if (t.consent?.status === 'notNeeded') return tr('consentNone');
  return '—';
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}
